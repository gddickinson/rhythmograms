// Studio files: save / load the configuration as JSON in the desktop's format (utils/config.py: version 1, the
// HarmonographConfig keys, "color", "effects"; the web adds "atmosphere", "projection" and "trail", which the
// desktop's from_dict methods ignore), PNG export (current view, or a full high-resolution render with effects, like
// utils/export.py export_png) and SVG export of the line trace.
import { download, rng } from './core.js';
import { configFromDict } from './harmonograph_engine.js';
import { prepareColor, colorAt } from './color.js';
import { renderFull, fullTrace, transforms } from './render.js';
import { applyEffects } from './postfx.js';
import { applyAtmosphere } from './atmosphere.js';
import { effectiveConfig } from './player.js';

export function configJson(st) {
  return JSON.stringify({ version: 1, ...st.h, color: st.c, effects: st.e, atmosphere: st.a, projection: st.p, trail: st.tr }, null, 2);
}

// Merge a loaded JSON file (desktop or web) into the state; unknown keys are ignored, missing ones keep defaults.
export function applyConfigJson(st, data, defaults) {
  st.h = configFromDict(data);
  st.en = st.h.pendulums.map(p => p.amplitude > 0);
  st.c = { ...defaults.color, ...(data.color || {}) };
  st.e = { ...defaults.effects, ...(data.effects || {}) };
  if (data.atmosphere) st.a = { ...defaults.atmosphere, ...data.atmosphere };
  if (data.projection) st.p = { ...defaults.projection, ...data.projection };
  if (data.trail) st.tr = { ...defaults.trail, ...data.trail };
}

export function pickFile(accept = '.json,application/json') {
  return new Promise(resolve => {
    const inp = document.createElement('input');
    inp.type = 'file'; inp.accept = accept;
    inp.addEventListener('change', async () => resolve(inp.files[0] ? await inp.files[0].text() : null));
    inp.click();
  });
}

export function saveView(canvas, name = 'rhythmogram.png') {
  canvas.toBlob(b => download(name, b), 'image/png');
}

// Full trace at size x size, with symmetry, 3D, post-processing and atmosphere as set in the Studio.
export async function renderPng(st, size, name = 'rhythmogram.png') {
  const c = document.createElement('canvas');
  c.width = size; c.height = size;
  const ctx = c.getContext('2d');
  renderFull(ctx, effectiveConfig(st), prepareColor(st.c), size, size, { proj: st.p, rand: rng(5) });
  const img = ctx.getImageData(0, 0, size, size);
  let px = applyEffects(img.data, size, size, st.e);
  px = applyAtmosphere(px, size, size, st.a);
  img.data.set(px);
  ctx.putImageData(img, 0, 0);
  await new Promise(res => c.toBlob(b => { download(name, b); res(); }, 'image/png'));
}

// SVG of the full trace as stroked polylines (one per run of equal colour/width), with symmetry and mirrors.
// Other brushes are drawn as lines; post-processing is raster-only (as in the desktop SVG export).
export function svgText(st, size = 2048) {
  const cc = prepareColor(st.c), tr = fullTrace(effectiveConfig(st), size, size, st.p);
  const out = [`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">`,
    '<title>Rhythmogram</title><desc>Generated by the Rhythmogram Simulator (web)</desc>',
    `<rect width="100%" height="100%" fill="${cc.bg_color}"/>`, '<g fill="none" stroke-linecap="round" stroke-linejoin="round">'];
  const f = v => v.toFixed(1);
  for (const T of transforms(cc, size / 2, size / 2)) {
    let key = '', pts = [];
    const flush = () => { if (pts.length > 1) out.push(`<polyline points="${pts.join(' ')}" ${key}/>`); pts = []; key = ''; };
    for (let i = 0; i + 1 < tr.n; i++) {
      if (Number.isNaN(tr.px.x[i]) || Number.isNaN(tr.px.x[i + 1])) { flush(); continue; }
      const col = colorAt(cc, i / Math.max(tr.n - 1, 1));
      const k = `stroke="rgb(${col[0]},${col[1]},${col[2]})" stroke-opacity="${(col[3] / 255).toFixed(2)}" stroke-width="${cc.line_width}"`;
      const [x1, y1] = T(tr.px.x[i], tr.px.y[i]), [x2, y2] = T(tr.px.x[i + 1], tr.px.y[i + 1]);
      if (k !== key || pts.length > 400) { flush(); key = k; pts.push(`${f(x1)},${f(y1)}`); }
      pts.push(`${f(x2)},${f(y2)}`);
    }
    flush();
  }
  out.push('</g></svg>');
  return out.join('\n');
}
